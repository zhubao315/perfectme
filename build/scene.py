def compute():
    """返回 (starts：镜号->成片起点秒, hardcut_total)。"""
    starts, t = {}, 0.0
    for i, sh in enumerate(SHOTS):
        starts[sh["id"]] = t - i * TR
        t += sh["dur"]
    return starts, t


def load_starts():
    """优先读取 build.py 生成的 timeline.json；缺失时按本表计算。"""
    if os.path.exists(TIMELINE):
        with open(TIMELINE, encoding="utf-8") as f:
            return json.load(f)
    return compute()[0]


def line_start(sid, off, starts=None):
    starts = starts or load_starts()
    return starts.get(sid, 0.0) + off


